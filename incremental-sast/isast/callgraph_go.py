"""Go call graph -> file-level neighbour map.

Go is the easy language here: go/ssa plus golang.org/x/tools/go/callgraph
give established algorithms (CHA, RTA, VTA, static). That reliability is
the whole reason Go is in the corpus alongside TypeScript, where the
call graph is far weaker. RQ4 tests whether that difference bounds the
benefit of context reuse.

This module shells out to a small Go helper (see cmd/callgraph/main.go,
generated by `write_helper()`) that emits caller/callee file pairs as JSON.
"""
from __future__ import annotations


import json
import subprocess
from collections import defaultdict
from pathlib import Path

HELPER_SRC = r'''
package main

// Emits file-level call edges as JSON: [{"from":"a.go","to":"b.go"}, ...]
// Build:  go build -o callgraph-helper .
// Usage:  ./callgraph-helper ./...

import (
	"encoding/json"
	"fmt"
	"go/token"
	"os"

	"golang.org/x/tools/go/callgraph"
	"golang.org/x/tools/go/callgraph/vta"
	"golang.org/x/tools/go/packages"
	"golang.org/x/tools/go/ssa"
	"golang.org/x/tools/go/ssa/ssautil"
)

type edge struct {
	From string `json:"from"`
	To   string `json:"to"`
}

func fileOf(fset *token.FileSet, fn *ssa.Function) string {
	if fn == nil || fn.Pos() == token.NoPos {
		return ""
	}
	return fset.Position(fn.Pos()).Filename
}

func main() {
	pattern := "./..."
	if len(os.Args) > 1 {
		pattern = os.Args[1]
	}
	cfg := &packages.Config{Mode: packages.LoadAllSyntax}
	pkgs, err := packages.Load(cfg, pattern)
	if err != nil {
		os.Exit(1)
	}
	// NOTE: ssa.InstantiateGenerics is deliberately NOT used. That mode
	// triggers a known x/tools SSA-builder crash ("unexpected expr:
	// *ast.KeyValueExpr") on composite literals inside generic code,
	// which manifested as unrecoverable fatal errors on 7 of 12 gitea
	// commits even with per-package panic recovery in place. Building
	// "shape" functions (mode 0) avoids the trigger entirely.
	prog, _ := ssautil.AllPackages(pkgs, 0)

	// Build per-package with panic recovery. The SSA builder has known
	// crashes on some composite-literal/generics patterns (e.g. "unexpected
	// expr: *ast.KeyValueExpr"); one bad package should not take down the
	// whole call graph. Skipped packages are reported on stderr so the
	// completeness stats reflect what was actually analyzed.
	var skipped int
	for _, p := range prog.AllPackages() {
		func() {
			defer func() {
				if r := recover(); r != nil {
					skipped++
					fmt.Fprintf(os.Stderr, "skipping package %v after SSA build panic: %v\n", p.Pkg.Path(), r)
				}
			}()
			p.Build()
		}()
	}
	if skipped > 0 {
		fmt.Fprintf(os.Stderr, "SSA_SKIPPED=%d\n", skipped)
	}

	cg := vta.CallGraph(ssautil.AllFunctions(prog), nil)
	cg.DeleteSyntheticNodes()

	seen := map[edge]bool{}
	out := []edge{}
	_ = callgraph.GraphVisitEdges(cg, func(e *callgraph.Edge) error {
		f := fileOf(prog.Fset, e.Caller.Func)
		t := fileOf(prog.Fset, e.Callee.Func)
		if f == "" || t == "" || f == t {
			return nil
		}
		k := edge{From: f, To: t}
		if !seen[k] {
			seen[k] = true
			out = append(out, k)
		}
		return nil
	})
	json.NewEncoder(os.Stdout).Encode(out)
}
'''

GO_MOD = """module callgraph-helper

go 1.21

require golang.org/x/tools v0.31.0
"""


def write_helper(dest: Path) -> Path:
    """Materialize the Go helper. Run `go mod tidy && go build` in dest."""
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "main.go").write_text(HELPER_SRC)
    (dest / "go.mod").write_text(GO_MOD)
    return dest


def neighbors(repo_root: Path, helper_bin: Path,
              bidirectional: bool = True) -> tuple[dict[str, set[str]], dict]:
    """file -> set of files one call-hop away.

    Returns (neighbour_map, stats). `stats` carries call-graph completeness,
    which RQ4 reports as an independent variable — do not discard it.
    """
    proc = subprocess.run(
        [str(helper_bin), "./..."],
        cwd=str(repo_root), capture_output=True, text=True, timeout=1800,
    )
    if proc.returncode != 0 or not proc.stdout.strip():
        return {}, {"ok": False, "stderr": proc.stderr[-2000:]}

    edges = json.loads(proc.stdout)
    nb: dict[str, set[str]] = defaultdict(set)
    root = str(repo_root.resolve())

    for e in edges:
        f, t = e["from"], e["to"]
        if not (f.startswith(root) and t.startswith(root)):
            continue  # skip stdlib and module cache
        f = f[len(root):].lstrip("/")
        t = t[len(root):].lstrip("/")
        nb[f].add(t)
        if bidirectional:
            nb[t].add(f)

    stats = {
        "ok": True,
        "n_edges": len(edges),
        "n_files_with_edges": len(nb),
    }
    return dict(nb), stats


def invalidation_set(changed: list[str], nb: dict[str, set[str]],
                     policy: str) -> set[str]:
    """Which files' cached summaries must be recomputed.

    direct     — only changed files
    one_hop    — plus immediate callers
    transitive — full caller closure

    Soundness rises and savings fall along this progression. Measuring
    where the acceptable point sits is a primary result (RQ3), and it is
    expected to differ between Go and TypeScript.
    """
    if policy == "direct":
        return set(changed)
    if policy == "one_hop":
        s = set(changed)
        for f in changed:
            s |= nb.get(f, set())
        return s
    if policy == "transitive":
        s, frontier = set(changed), set(changed)
        while frontier:
            nxt = set()
            for f in frontier:
                nxt |= nb.get(f, set())
            nxt -= s
            s |= nxt
            frontier = nxt
        return s
    raise ValueError(f"unknown policy: {policy}")